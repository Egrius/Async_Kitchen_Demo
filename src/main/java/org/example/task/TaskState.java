package org.example.task;

public enum TaskState {
    /** Задача создана, но ещё не запущена. */
    CREATED,
    /** Задача выполняется. */
    RUNNING,
    /** Задача вытеснена VIP-заказом (ожидает восстановления). */
    DISPLACED,
    /** Задача успешно завершена. */
    COMPLETED,
    /** Задача завершена с ошибкой (например, после исчерпания ретраев). */
    FAILED
}
